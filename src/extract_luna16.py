import os
import glob
import pandas as pd
import numpy as np
import SimpleITK as sitk

def extract_luna16_rois():
    print("=== 🚀 Starting LUNA16 physical-space ROI extraction and manifest generation ===")
    
    # ==========================================
    # 📁 1. Path configuration (adjust these paths for your environment).
    # ==========================================
    # Official LUNA16 annotation file containing nodule coordinates and diameters.
    annotations_path = "data/LUNA16/annotations.csv" 
    # Raw data directory used to read the physical origin metadata from MHD files.
    raw_luna_dir = "data/LUNA16/"
    # Directory containing normalized full-volume arrays generated by preprocess.py.
    preprocessed_dir = "data/processed/preprocessed_cubes/"
    
    # Output paths.
    out_cube_dir = "data/processed/luna16_roi_cubes/"
    out_manifest_path = "data/processed/luna16_dataset_manifest.csv"
    
    os.makedirs(out_cube_dir, exist_ok=True)
    
    if not os.path.exists(annotations_path):
        print(f"\n❌ Error: Official LUNA16 annotations were not found: {annotations_path}")
        print("Download annotations.csv and place it in the data/LUNA16/ directory.")
        return

    # ==========================================
    # 📖 2. Read LUNA16 annotations and start processing.
    # ==========================================
    annotations = pd.read_csv(annotations_path)
    print(f"✅ Loaded annotations.csv with {len(annotations)} official nodule annotations.")
    
    manifest_records = []
    success_count = 0
    missing_files = set()

    for idx, row in annotations.iterrows():
        uid = str(row['seriesuid'])
        coord_x = float(row['coordX'])
        coord_y = float(row['coordY'])
        coord_z = float(row['coordZ'])
        diameter = float(row['diameter_mm'])
        
        # Find the corresponding full-volume array.
        npy_path = os.path.join(preprocessed_dir, f"{uid}_preprocessed.npy")
        if not os.path.exists(npy_path):
            missing_files.add(uid)
            continue
            
        # Find the original MHD file to obtain the physical origin and direction.
        # Preprocessing changed spacing to 1x1x1 but left the origin unchanged.
        mhd_files = glob.glob(os.path.join(raw_luna_dir, "**", f"{uid}.mhd"), recursive=True)
        if not mhd_files:
            missing_files.add(uid)
            continue
            
        mhd_path = mhd_files[0]
        
        # ==========================================
        # 📐 3. Map physical coordinates to array indices (core algorithm).
        # ==========================================
        try:
            # Read MHD metadata efficiently (header only, without loading pixel data).
            reader = sitk.ImageFileReader()
            reader.SetFileName(mhd_path)
            reader.ReadImageInformation()
            origin = reader.GetOrigin()
            direction = reader.GetDirection()
            
            # Load the preprocessed full-volume NumPy array.
            lung_array = np.load(npy_path)
            D, H, W = lung_array.shape
            
            # Create a virtual SimpleITK image to use its physical-coordinate mapping.
            # Note: SimpleITK size is [X, Y, Z], corresponding to NumPy [W, H, D].
            dummy_img = sitk.Image([W, H, D], sitk.sitkUInt8)
            dummy_img.SetOrigin(origin)
            dummy_img.SetDirection(direction)
            dummy_img.SetSpacing([1.0, 1.0, 1.0]) # Preprocessing resampled spacing to 1x1x1.
            
            # Map physical coordinates to array indices.
            physical_point = (coord_x, coord_y, coord_z)
            idx_x, idx_y, idx_z = dummy_img.TransformPhysicalPointToIndex(physical_point)
            
            # Convert to NumPy (Depth, Height, Width) order.
            center_d, center_h, center_w = idx_z, idx_y, idx_x
            
            # ==========================================
            # ✂️ 4. Crop a 32x32x32 local ROI with boundary checks.
            # ==========================================
            half_size = 16
            d_start, d_end = center_d - half_size, center_d + half_size
            h_start, h_end = center_h - half_size, center_h + half_size
            w_start, w_end = center_w - half_size, center_w + half_size
            
            # Preprocessing normalized [-1000, 400] to [0, 1], where air (-1000) is 0.0.
            # Use 0.0 as the padding value for background voxels.
            roi_cube = np.zeros((32, 32, 32), dtype=np.float32)
            
            # Calculate valid crop boundaries.
            d_start_v, d_end_v = max(0, d_start), min(D, d_end)
            h_start_v, h_end_v = max(0, h_start), min(H, h_end)
            w_start_v, w_end_v = max(0, w_start), min(W, w_end)
            
            # Skip if the center point lies completely outside the volume.
            if d_start_v >= d_end_v or h_start_v >= h_end_v or w_start_v >= w_end_v:
                continue
                
            # Calculate the destination offsets in roi_cube.
            roi_d_start = d_start_v - d_start
            roi_d_end = 32 - (d_end - d_end_v)
            roi_h_start = h_start_v - h_start
            roi_h_end = 32 - (h_end - h_end_v)
            roi_w_start = w_start_v - w_start
            roi_w_end = 32 - (w_end - w_end_v)
            
            # Copy the cropped volume data.
            roi_cube[roi_d_start:roi_d_end, roi_h_start:roi_h_end, roi_w_start:roi_w_end] = \
                lung_array[d_start_v:d_end_v, h_start_v:h_end_v, w_start_v:w_end_v]
            
            # ==========================================
            # 💾 5. Generate proxy labels and save the ROI.
            # ==========================================
            # Proxy rule: diameter >= 8 mm is high-risk/malignant (1); otherwise benign (0).
            binary_label = 1 if diameter >= 8.0 else 0
            binary_desc = "Malignant nodule" if binary_label == 1 else "Benign nodule"
            
            roi_filename = f"{uid}_nodule_{idx}.npy"
            roi_save_path = os.path.join(out_cube_dir, roi_filename)
            
            np.save(roi_save_path, roi_cube)
            
            # Add a record to the manifest using columns expected by the dataset loader.
            manifest_records.append({
                "patient_id": uid,
                "cube_file_path": roi_filename,
                "diameter_mm": diameter,
                "binary_label": binary_label,
                "binary_desc": binary_desc
            })
            
            success_count += 1
            if success_count % 50 == 0:
                print(f"  -> Successfully processed {success_count} nodules...")
                
        except Exception as e:
            print(f"⚠️ Error processing lesion {uid}: {e}")
            continue

    # ==========================================
    # 📝 6. Save the final manifest.
    # ==========================================
    df_manifest = pd.DataFrame(manifest_records)
    df_manifest.to_csv(out_manifest_path, index=False, encoding='utf-8-sig')
    
    print("\n==================================================")
    print("🎉 LUNA16 ROI extraction complete.")
    print(f"✅ Successfully extracted {success_count} 3D ROI arrays.")
    print(f"📄 Generalization test manifest saved to: {out_manifest_path}")
    if missing_files:
        print(f"⚠️ Skipped {len(missing_files)} UIDs with missing MHD or NPY files.")
    print("==================================================")

if __name__ == "__main__":
    extract_luna16_rois()
